import "server-only";
import { PDFDocument, StandardFonts, rgb } from "pdf-lib";

export type PayslipPdfInput = {
  companyName: string;
  employeeName: string;
  employeeCode: string;
  departmentName: string | null;
  month: string;
  basic: number;
  hra: number;
  medical: number;
  gross: number;
  workingDays: number;
  perDay: number;
  absentDays: number;
  unpaidDays: number;
  halfDays: number;
  deductions: number;
  tax: number;
  net: number;
};

function money(value: number): string {
  return Number(value).toLocaleString("en-US", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
}

/** Render a one-page payslip PDF (standard Helvetica fonts). */
export async function buildPayslipPdf(data: PayslipPdfInput): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  const page = doc.addPage([595.28, 841.89]); // A4 portrait
  const regular = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);

  const marginX = 56;
  const width = page.getWidth();
  let y = page.getHeight() - 64;

  const text = (
    value: string,
    options: { size?: number; bold?: boolean; color?: [number, number, number] } = {}
  ) => {
    page.drawText(value, {
      x: marginX,
      y,
      size: options.size ?? 10,
      font: options.bold ? bold : regular,
      color: options.color ? rgb(...options.color) : rgb(0.1, 0.1, 0.12),
    });
  };

  const row = (label: string, value: string) => {
    page.drawText(label, {
      x: marginX,
      y,
      size: 10,
      font: regular,
      color: rgb(0.35, 0.36, 0.4),
    });
    const valueWidth = regular.widthOfTextAtSize(value, 10);
    page.drawText(value, {
      x: width - marginX - valueWidth,
      y,
      size: 10,
      font: bold,
      color: rgb(0.1, 0.1, 0.12),
    });
    y -= 17;
  };

  const divider = () => {
    page.drawLine({
      start: { x: marginX, y },
      end: { x: width - marginX, y },
      thickness: 0.75,
      color: rgb(0.85, 0.86, 0.88),
    });
    y -= 22;
  };

  text(data.companyName || "HCM Lite", { size: 18, bold: true });
  y -= 22;
  text("PAYSLIP", { size: 12, bold: true, color: [0.35, 0.36, 0.4] });
  y -= 16;
  text(`Month: ${data.month}`, { size: 11 });
  y -= 26;
  divider();

  text("Employee", { size: 11, bold: true });
  y -= 17;
  row("Name", data.employeeName);
  row("Code", data.employeeCode);
  row("Department", data.departmentName ?? "—");
  y -= 4;
  divider();

  text("Earnings", { size: 11, bold: true });
  y -= 17;
  row("Basic", money(data.basic));
  row("HRA (40%)", money(data.hra));
  row("Medical (10%)", money(data.medical));
  row("Gross", money(data.gross));
  y -= 4;
  divider();

  text("Attendance", { size: 11, bold: true });
  y -= 17;
  row("Working days", String(data.workingDays));
  row("Per day", money(data.perDay));
  row("Absent days", String(data.absentDays));
  row("Unpaid leave days", String(data.unpaidDays));
  row("Half days", String(data.halfDays));
  y -= 4;
  divider();

  text("Deductions & tax", { size: 11, bold: true });
  y -= 17;
  row("Absence deductions", money(data.deductions));
  row("Tax", money(data.tax));
  y -= 4;
  divider();

  page.drawText("NET PAY", {
    x: marginX,
    y,
    size: 13,
    font: bold,
    color: rgb(0.1, 0.1, 0.12),
  });
  const netText = money(data.net);
  const netWidth = bold.widthOfTextAtSize(netText, 13);
  page.drawText(netText, {
    x: width - marginX - netWidth,
    y,
    size: 13,
    font: bold,
    color: rgb(0.1, 0.1, 0.12),
  });

  const footerY = 56;
  page.drawText("Generated by HCM Lite", {
    x: marginX,
    y: footerY,
    size: 9,
    font: regular,
    color: rgb(0.55, 0.56, 0.6),
  });
  const stamp = new Date().toISOString().slice(0, 10);
  const stampWidth = regular.widthOfTextAtSize(stamp, 9);
  page.drawText(stamp, {
    x: width - marginX - stampWidth,
    y: footerY,
    size: 9,
    font: regular,
    color: rgb(0.55, 0.56, 0.6),
  });

  return doc.save();
}
